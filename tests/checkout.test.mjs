import test from 'node:test';
import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const source=readFileSync('src/lib/checkout.ts','utf8');
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const module={exports:{}};
vm.runInNewContext(output,{module,exports:module.exports,require});
const {checkoutSchema,consolidateItems}=module.exports;
const id='11111111-1111-4111-8111-111111111111';
const requestId='aaaaaaa1-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const input={requestId,items:[{id,size:'M',quantity:2}],customer:{name:'Pembeli Test',email:'test@example.com',address:'Jalan Contoh No 10, Indonesia'},paymentMethod:'demo_card',simulate:'success'};
test('valid dummy checkout',()=>assert.equal(checkoutSchema.safeParse(input).success,true));
test('reject invalid email and missing shipping address',()=>assert.equal(checkoutSchema.safeParse({...input,customer:{...input.customer,email:'wrong',address:''}}).success,false));
test('reject unsupported real payment method',()=>assert.equal(checkoutSchema.safeParse({...input,paymentMethod:'real_card'}).success,false));
test('reject empty checkout and oversized quantities',()=>{assert.equal(checkoutSchema.safeParse({...input,items:[]}).success,false);assert.equal(checkoutSchema.safeParse({...input,items:[{id,size:'M',quantity:21}]}).success,false)});
test('aggregate duplicate lines before stock verification',()=>{const list=consolidateItems([{id,size:'M',quantity:2},{id,size:'M',quantity:3}]);assert.equal(list.length,1);assert.equal(list[0].quantity,5)});
test('reject combined quantity above limit',()=>assert.throws(()=>consolidateItems([{id,size:'M',quantity:15},{id,size:'M',quantity:6}]),{name:'RangeError'}));
test('reject extra request fields',()=>assert.equal(checkoutSchema.safeParse({...input,token:'123'}).success,false));
